// The mail-link write path (NS-158, VER-007, INB-009/011). Tags are generated by the caller
// (packages/inbox, generateTag) and only stored here; links record what matchMail decided.
// Events carry Gmail ids, steps, reasons and application ids: never an address, subject,
// sender or body.

const TAG = /^[a-z2-7]{6}$/;
const TENANT_KEY = /^[a-z0-9]+:[a-z0-9]+([_.-][a-z0-9]+)*$/;
const UNIQUE_VIOLATION = "23505";
// A collision is 1 in 2^30 per pair; three fresh tags in a row colliding means the generator
// is broken, so stop instead of looping.
const TAG_ATTEMPTS = 3;

type Tx = Parameters<Parameters<Db["transaction"]>[0]>[0];

export type TagTarget = { applicationId: string } | { tenantKey: string };
export type TagView = { tag: string; applicationId: string | null; tenantKey: string | null };

const isUniqueViolation = (error: unknown): boolean => {
  const codeOf = (e: unknown) =>
    typeof e === "object" && e !== null && "code" in e ? (e as { code: unknown }).code : undefined;
  return (
    codeOf(error) === UNIQUE_VIOLATION ||
    (typeof error === "object" && error !== null && "cause" in error
      ? codeOf((error as { cause: unknown }).cause) === UNIQUE_VIOLATION
      : false)
  );
};

async function existingTag(tx: Tx | Db, candidateId: CandidateId, target: TagTarget) {
  const [row] = await tx
    .select({ tag: mailTag.tag })
    .from(mailTag)
    .where(
      and(
        eq(mailTag.candidateId, candidateId),
        "applicationId" in target
          ? eq(mailTag.applicationId, target.applicationId)
          : eq(mailTag.tenantKey, target.tenantKey),
      ),
    );
  return row?.tag;
}

// The tag for an application or a tenant: its existing one, or a new one from newTag. Safe to
// repeat: an application or tenant keeps its first tag (a partial unique index backs this).
export async function assignTag(
  db: Db,
  input: { candidateId: CandidateId; target: TagTarget; newTag: () => string },
): Promise<{ tag: string; created: boolean }> {
  if ("tenantKey" in input.target && !TENANT_KEY.test(input.target.tenantKey)) {
    throw new Error("invalid tenant key");
  }
  return inSpan(
    "db.mail_tag.assign",
    { "northstar.mail_tag.target": "applicationId" in input.target ? "application" : "tenant" },
    async () => {
      for (let attempt = 0; attempt < TAG_ATTEMPTS; attempt++) {
        const tag = input.newTag();
        if (!TAG.test(tag)) throw new Error("newTag returned something that isn't a mail tag");
        try {
          return await db.transaction(async (tx) => {
            // One assignment per target at a time, so two callers can't both create one.
            const key =
              "applicationId" in input.target
                ? `application:${input.target.applicationId}`
                : `tenant:${input.target.tenantKey}`;
            await tx.execute(
              sql`select pg_advisory_xact_lock(hashtext(${`mail_tag:${input.candidateId}:${key}`}))`,
            );
            const existing = await existingTag(tx, input.candidateId, input.target);
            if (existing !== undefined) return { tag: existing, created: false };
            await tx.insert(mailTag).values({
              candidateId: input.candidateId,
              tag,
              applicationId: "applicationId" in input.target ? input.target.applicationId : null,
              tenantKey: "tenantKey" in input.target ? input.target.tenantKey : null,
            });
            return { tag, created: true };
          });
        } catch (error) {
          // The tag itself collided with another one: try a fresh tag.
          if (!isUniqueViolation(error)) throw error;
        }
      }
      throw new Error("could not find an unused mail tag");
    },
  );
}

// One application's tag, or null when it has none yet: read-only, for the Gate's check that a
// package's tagged address is this application's own (NS-248).
export async function readApplicationTag(
  db: Db,
  candidateId: CandidateId,
  applicationId: string,
): Promise<string | null> {
  // Not an id at all names no application (and would be a type error in Postgres).
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(applicationId))
    return null;
  return (await existingTag(db, candidateId, { applicationId })) ?? null;
}

// Every tag of this candidate, for matchMail.
export async function readTags(db: Db, candidateId: CandidateId): Promise<TagView[]> {
  return db
    .select({
      tag: mailTag.tag,
      applicationId: mailTag.applicationId,
      tenantKey: mailTag.tenantKey,
    })
    .from(mailTag)
    .where(eq(mailTag.candidateId, candidateId))
    .orderBy(asc(mailTag.createdAt));
}

// The Gmail threads already linked to each application, for matchMail's step 2.
export async function readLinkedThreads(
  db: Db,
  candidateId: CandidateId,
): Promise<Map<string, string[]>> {
  // Only matching's own links: a thread Paul linked from the confirm queue (NS-262) doesn't count,
  // since its unknown first sender could then reply through a shared ATS and pass as verified.
  const rows = await db
    .selectDistinct({ applicationId: mailLink.applicationId, threadId: mailLink.gmailThreadId })
    .from(mailLink)
    .where(and(eq(mailLink.candidateId, candidateId), isNotNull(mailLink.applicationId)));
  const out = new Map<string, string[]>();
  for (const r of rows) {
    if (r.applicationId === null) continue;
    out.set(r.applicationId, [...(out.get(r.applicationId) ?? []), r.threadId]);
  }
  return out;
}

export type LinkCandidateRow = {
  applicationId: string;
  // When it was started: mail about it can arrive from then on.
  createdAt: Date;
  // The job's ATS and every source's ATS, each once, in a fixed order. Empty when none is known.
  ats: (typeof ATS_KINDS)[number][];
  // The job's company's own mail domains, as Paul entered them (NS-252). Left out when none are
  // set, so a row reads as before for a company without domains.
  companyDomains?: string[];
};

// Statuses mail may still arrive for: every one with a move left (a ghosted application can be
// revived by a late reply). Rejected and withdrawn applications are closed, so a tag for one goes
// to Paul's confirm queue instead of linking (matchMail).
const OPEN_STATUSES = APPLICATION_STATUSES.filter((s) => !isTerminal(s));

// The applications mail can be linked to, for matchMail's candidates (#224). Ids, times, ATS
// names and the company's own domains (NS-252) only: no company name, title or address. Read-only.
export async function readLinkCandidates(
  db: Db,
  candidateId: CandidateId,
): Promise<LinkCandidateRow[]> {
  const apps = await db
    .select({
      applicationId: application.id,
      createdAt: application.createdAt,
      jobId: application.jobId,
      jobAts: job.ats,
      companyId: job.companyId,
    })
    .from(application)
    .innerJoin(
      job,
      and(eq(job.id, application.jobId), eq(job.candidateId, application.candidateId)),
    )
    .where(
      and(eq(application.candidateId, candidateId), inArray(application.status, OPEN_STATUSES)),
    )
    .orderBy(asc(application.createdAt), asc(application.id));
  if (apps.length === 0) return [];
  const sources = await db
    .selectDistinct({ jobId: jobSource.jobId, ats: jobSource.ats })
    .from(jobSource)
    .where(
      and(
        eq(jobSource.candidateId, candidateId),
        inArray(
          jobSource.jobId,
          apps.map((a) => a.jobId),
        ),
        isNotNull(jobSource.ats),
      ),
    );
  const domains = new Map(
    (await readCompanyDomains(db, candidateId)).map((c) => [c.companyId, c.domains]),
  );
  return apps.map((a) => {
    const names = new Set<string>();
    if (a.jobAts !== null) names.add(a.jobAts);
    for (const s of sources) if (s.jobId === a.jobId && s.ats !== null) names.add(s.ats);
    return {
      applicationId: a.applicationId,
      createdAt: a.createdAt,
      // The CHECK constraints allow only these names; sorted so the order never depends on rows.
      ats: [...names].sort() as LinkCandidateRow["ats"],
      ...companyDomainsOf(a.companyId === null ? [] : (domains.get(a.companyId) ?? [])),
    };
  });
}

// The field only when there are domains to give.
const companyDomainsOf = (d: string[]) => (d.length > 0 ? { companyDomains: d } : {});

export type LinkDecision =
  | {
      kind: "linked";
      applicationId: string;
      step: (typeof MATCH_STEPS)[number];
      senderVerified: boolean;
    }
  | { kind: "queued"; reason: (typeof QUEUE_REASONS)[number] };

export type RecordLinkInput = {
  candidateId: CandidateId;
  message: { id: string; threadId: string; receivedAt: Date };
  decision: LinkDecision;
};

// Records what matching decided for one message, once: a repeat for the same message stores
// nothing and writes no event (`recorded: false`). A link never changes a status (INB-004, P1).
export async function recordMailLink(
  db: Db,
  input: RecordLinkInput,
): Promise<{ recorded: boolean }> {
  const d = input.decision;
  return inSpan(
    "db.mail_link.record",
    { "northstar.mail_link.outcome": d.kind === "linked" ? d.step : d.reason },
    (span) =>
      db.transaction(async (tx) => {
        const [row] = await tx
          .insert(mailLink)
          .values({
            candidateId: input.candidateId,
            gmailMessageId: input.message.id,
            gmailThreadId: input.message.threadId,
            applicationId: d.kind === "linked" ? d.applicationId : null,
            step: d.kind === "linked" ? d.step : null,
            queueReason: d.kind === "queued" ? d.reason : null,
            senderVerified: d.kind === "linked" ? d.senderVerified : false,
            receivedAt: input.message.receivedAt,
          })
          .onConflictDoNothing({ target: [mailLink.candidateId, mailLink.gmailMessageId] })
          .returning({ id: mailLink.id, linkedAt: mailLink.linkedAt });
        if (!row) return { recorded: false };
        await appendEvent(tx, span, {
          candidateId: input.candidateId,
          aggregate: `mail_link:${row.id}`,
          type: d.kind === "linked" ? "mail.linked" : "mail.link_queued",
          actor: "system",
          reason: "",
          payload:
            d.kind === "linked"
              ? {
                  gmailMessageId: input.message.id,
                  applicationId: d.applicationId,
                  step: d.step,
                  senderVerified: d.senderVerified,
                }
              : { gmailMessageId: input.message.id, reason: d.reason },
          idempotencyKey: `mail_link:${input.candidateId}:${input.message.id}`,
          at: row.linkedAt,
        });
        return { recorded: true };
      }),
  );
}

export type QueuedMail = {
  gmailMessageId: string;
  gmailThreadId: string;
  reason: (typeof QUEUE_REASONS)[number];
  receivedAt: Date;
};

// The "confirm link" queue: messages matching couldn't place, oldest first.
export async function listConfirmQueue(db: Db, candidateId: CandidateId): Promise<QueuedMail[]> {
  const rows = await db
    .select({
      gmailMessageId: mailLink.gmailMessageId,
      gmailThreadId: mailLink.gmailThreadId,
      reason: mailLink.queueReason,
      receivedAt: mailLink.receivedAt,
    })
    .from(mailLink)
    // A message Paul decided (NS-262) has left the queue.
    .leftJoin(
      mailLinkDecision,
      and(
        eq(mailLinkDecision.candidateId, mailLink.candidateId),
        eq(mailLinkDecision.gmailMessageId, mailLink.gmailMessageId),
      ),
    )
    .where(
      and(
        eq(mailLink.candidateId, candidateId),
        isNull(mailLink.applicationId),
        isNull(mailLinkDecision.id),
      ),
    )
    .orderBy(asc(mailLink.receivedAt));
  return rows.map((r) => ({ ...r, reason: r.reason as QueuedMail["reason"] }));
}
